"""Finds the default attention weights for the page and writes them to weights.js.

The embeddings are set by hand (so that similar words are visibly close); only the four
attention matrices (Wq, Wk, Wv, Wo) are trained, with Adam on a tiny corpus. The result is
rounded to 2 decimals so the numbers on the page are short and exact in every language.

Usage:  python tools/train_weights.py        (deterministic: same seed, same weights.js)
"""
import json
import pathlib

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent

VOCAB = ["the", "cat", "dog", "sat", "ran", "on", "mat", "."]
DIMS = ["animal", "place", "action", "grammar"]
# One row per token, one column per dimension in DIMS.
EMBED = [
    [0.0, 0.0, 0.0, 1.0],   # the
    [1.0, 0.0, 0.1, 0.0],   # cat
    [0.9, 0.0, 0.3, 0.0],   # dog
    [0.0, 0.2, 1.0, 0.0],   # sat
    [0.1, 0.0, 1.0, 0.0],   # ran
    [0.0, 0.6, 0.0, 0.6],   # on
    [0.0, 1.0, 0.0, 0.0],   # mat
    [0.0, 0.0, 0.0, -1.0],  # .
]
CORPUS = [
    "the cat sat on the mat .",
    "the dog sat on the mat .",
    "the cat ran on the mat .",
    "the dog ran on the mat .",
]
SEED = 7
STEPS = 3000
LR = 0.03


def positional(n, d):
    """Sinusoidal position encoding from 'Attention Is All You Need'."""
    pos = np.arange(n)[:, None]
    i = np.arange(d // 2)[None, :]
    angle = pos / 10000 ** (2 * i / d)
    pe = np.zeros((n, d))
    pe[:, 0::2] = np.sin(angle)
    pe[:, 1::2] = np.cos(angle)
    return pe


def forward(ids, E, Wq, Wk, Wv, Wo):
    """Same maths as model.js: returns logits for every position, shape (n, V)."""
    n, d = len(ids), E.shape[1]
    X = E[ids] + positional(n, d)
    Q, K, V = X @ Wq, X @ Wk, X @ Wv
    S = Q @ K.T / np.sqrt(d)
    S = np.where(np.tril(np.ones((n, n))) == 1, S, -np.inf)
    A = np.exp(S - S.max(axis=1, keepdims=True))
    A /= A.sum(axis=1, keepdims=True)
    H = X + (A @ V) @ Wo
    return H @ E.T


def loss(params, E, data):
    Wq, Wk, Wv, Wo = params.reshape(4, *E.shape[1:], E.shape[1])
    total, count = 0.0, 0
    for ids in data:
        logits = forward(ids[:-1], E, Wq, Wk, Wv, Wo)
        logits -= logits.max(axis=1, keepdims=True)
        logp = logits - np.log(np.exp(logits).sum(axis=1, keepdims=True))
        total -= logp[np.arange(len(ids) - 1), ids[1:]].sum()
        count += len(ids) - 1
    return total / count


def numerical_grad(f, x, eps=1e-5):
    g = np.zeros_like(x)
    for i in range(x.size):
        x[i] += eps
        up = f(x)
        x[i] -= 2 * eps
        down = f(x)
        x[i] += eps
        g[i] = (up - down) / (2 * eps)
    return g


def main():
    E = np.array(EMBED)
    d = E.shape[1]
    data = [np.array([VOCAB.index(w) for w in s.split()]) for s in CORPUS]
    rng = np.random.default_rng(SEED)
    params = rng.uniform(-0.5, 0.5, 4 * d * d)
    m, v = np.zeros_like(params), np.zeros_like(params)
    f = lambda p: loss(p, E, data)  # noqa: E731
    for t in range(1, STEPS + 1):
        g = numerical_grad(f, params)
        m = 0.9 * m + 0.1 * g
        v = 0.999 * v + 0.001 * g * g
        params -= LR * (m / (1 - 0.9**t)) / (np.sqrt(v / (1 - 0.999**t)) + 1e-8)
        if t % 500 == 0:
            print(f"step {t}: loss {f(params):.4f}")
    params = np.round(params, 2)
    print(f"rounded: loss {f(params):.4f}")
    Wq, Wk, Wv, Wo = (m.tolist() for m in params.reshape(4, d, d))
    weights = {"vocab": VOCAB, "dims": DIMS, "corpus": CORPUS, "E": EMBED, "Wq": Wq, "Wk": Wk, "Wv": Wv, "Wo": Wo}
    body = json.dumps(weights).replace("], [", "],\n    [").replace('], "', '],\n  "')
    (ROOT / "weights.js").write_text(
        "// Generated by tools/train_weights.py. Don't edit by hand; change the script and rerun it.\n"
        "// Embeddings are hand-set; the attention matrices were trained on a four-sentence corpus.\n"
        f"globalThis.LLM_WEIGHTS = {body};\n"
    )
    print("wrote weights.js")


if __name__ == "__main__":
    main()
